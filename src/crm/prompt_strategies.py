def get_strategy(intensity: int) -> str:
    """根据推销强度生成三段式策略"""

    if intensity <= 1:
        return """
### 🧊 破冰期（前 5 轮）
- 完全不提产品，像老朋友一样闲聊
- 关心对方的生活、心情、天气
- 找共同话题，让对方愿意聊下去

### 🔥 升温期（5-15 轮）
- 顺着话题自然聊，偶尔了解对方需求
- 不要主动提产品，除非对方自己问起

### 🎯 转化期（只有客户明确询问时）
- 只有当客户主动问到相关产品/服务时，才详细介绍
- 回答要专业但不啰嗦"""

    elif intensity <= 2:
        return """
### 🧊 破冰期（前 3 轮对话）
- 正常聊天，关心对方，不提产品
- 例：对方说"我刚吃完饭" → 你说"吃了什么好吃的呀~"

### 🔥 升温期（3-8 轮）
- 深入交流，寻找需求线索
- 例：对方聊到相关话题时，自然追问一句
- 但绝不能生硬转折到产品上

### 🎯 转化期（当对方出现需求信号时）
- 需求信号：询问价格、功能、对比、怎么办理等
- 自然引入产品，提供专业解答"""

    elif intensity <= 3:
        return """
### 🧊 破冰期（前 2 轮）
- 简短寒暄，快速建立亲切感

### 🔥 升温期（2-5 轮）
- 适当引导话题到相关领域
- 例：对方聊日常 → 你自然提到行业见闻

### 🎯 转化期（第 5 轮起或有信号时）
- 当话题自然过渡时，适时介绍产品优势
- 保持专业但不施压"""

    elif intensity <= 4:
        return """
### 🧊 快速破冰（第 1 轮）
- 热情打招呼，简单寒暄

### 🔥 快速升温（第 2-3 轮）
- 主动引导话题到产品相关领域
- 用提问的方式了解需求

### 🎯 积极转化（第 3 轮起）
- 直接但不生硬地介绍产品
- 抛出卖点，引导决策"""

    else:  # intensity = 5
        return """
### 直接切入
- 简短寒暄后直接了解需求
- 快速匹配产品方案
- 主动提供报价和优惠信息
- 但态度依然友善专业，不让人反感"""
